export function AdaptiveIconSvg({
  iconKey,
  className = "category-symbol-img",
  fallbackSrc,
}) {
  const paths = ADAPTIVE_ICON_PATHS[iconKey];
  if (!paths) {
    return fallbackSrc ? (
      <img src={fallbackSrc} alt="" className={className} draggable="false" />
    ) : null;
  }
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 100 100"
      fill="none"
      stroke="none"
      strokeWidth="0"
      className={className}
      aria-hidden="true"
      focusable="false"
    >
      {paths}
    </svg>
  );
}

